    def resolve(self, message: str) -> dict:
        original = str(message or "")
        size = len(original.encode("utf-8"))
        if not original.strip():
            raise DispatchError("empty_message", "Type or paste a message before resolving it")
        if size > MAX_MESSAGE_BYTES:
            raise DispatchError("message_too_large", f"Dispatch messages are limited to {MAX_MESSAGE_BYTES} bytes")
        sha256 = _sha256(original)
        targets, brain_terms, board_available = self._collect_targets(original)
        query_terms = _tokens(original)
        exact_ids = {value.lower() for value in UUID_RE.findall(original)}
        asks_claude = "claude" in query_terms or "anthropic" in query_terms
        asks_codex = bool({"codex", "chatgpt", "openai"} & query_terms)

        scored: list[dict] = []
        for target in targets:
            title_terms = _tokens(target["title"])
            routing_terms = _tokens(target.get("_routingText", ""))
            score = 0
            reasons: list[str] = []
            if target["id"].lower() in exact_ids:
                score += 1000
                reasons.append("exact ID")
            provider_requested = asks_claude or asks_codex
            provider_matches = (asks_claude and target["provider"] == "claude") or (
                asks_codex and target["provider"] == "codex"
            )
            if provider_matches:
                score += 18
                reasons.append("provider named")
            elif provider_requested:
                score -= 18
            title_overlap = query_terms & title_terms
            evidence_overlap = query_terms & routing_terms
            brain_overlap = title_terms & brain_terms
            project_overlap = query_terms & _tokens(target.get("projectName") or "")
            score += len(title_overlap) * 10
            score += len(evidence_overlap - title_overlap) * 3
            score += len(brain_overlap) * 4
            score += len(project_overlap - title_overlap) * 8
            if title_overlap:
                reasons.append("task title match")
            if evidence_overlap - title_overlap:
                reasons.append("owner/session evidence")
            if brain_overlap:
                reasons.append("connected Brain metadata")
            if project_overlap:
                reasons.append("exact project Brain association")
            if target.get("_board"):
                score += 2
            candidate = dict(target)
            candidate["score"] = score
            candidate["reason"] = ", ".join(reasons) or "No material routing evidence"
            scored.append(candidate)
        scored.sort(key=lambda item: (-item["score"], item["provider"], item["title"].lower(), item["id"]))

        resolution_id = "resolution_" + secrets.token_hex(12)
        expires = time.time() + 300
        state = "no target"
        choices: list[dict] = []
        target = None
        reason = "No existing owner or live session matched strongly enough; Dispatch will not create one."
        if scored and scored[0]["score"] >= 8:
            top = scored[0]
            second = scored[1] if len(scored) > 1 else None
            ambiguous = bool(
                top["score"] < 1000
                and second
                and second["score"] >= 8
                and second["score"] >= max(top["score"] - 4, top["score"] * 0.82)
            )
            if ambiguous:
                state = "ambiguous"
                choices = [item for item in scored[:3] if item["score"] >= 8]
                reason = "Several existing destinations have materially similar evidence; choose exactly one."
            else:
                state = "resolved"
                target = top
                choices = [top]
                brain_phrase = (
                    "Exact project/Brain association and "
                    if top.get("brainId")
                    else "Connected Brain metadata and "
                    if brain_terms
                    else ""
                )
                owner_phrase = "current Agent Board/session evidence" if board_available else "existing session metadata"
                reason = f"{brain_phrase}{owner_phrase} identify this as the materially strongest existing destination."

        with self._lock:
            self._resolutions[resolution_id] = {
                "createdAt": time.time(),
                "expiresAt": expires,
                "sha256": sha256,
                "state": state,
                "candidates": {item["id"]: item for item in choices},
                "reason": reason,
            }
            self._resolutions = {
                key: value for key, value in self._resolutions.items() if value["expiresAt"] >= time.time()
            }
        if state in {"ambiguous", "no target"}:
            self._history_entry(None, sha256, reason, state, False)
        return {
            "ok": state == "resolved",
            "schemaVersion": SCHEMA_VERSION,
            "state": state,
            "resolutionId": resolution_id,
            "messageSha256": sha256,
            "reason": reason,
            "target": self._public_target(target) if target else None,
            "choices": [self._public_target(item) for item in choices],
            "expiresAtEpoch": expires,
            "privacy": self._privacy(),
        }

    def _permission_bypass_verified(self) -> bool:
        observed, cached = self._permission_audit
        now = time.monotonic()
        if observed is not None:
            age = now - observed
            if 0.0 <= age < PERMISSION_AUDIT_CACHE_SECONDS:
                return cached
        audit = self.home / ".codex" / "skills" / "maintain-full-access-plus" / "scripts" / "audit.zsh"
        if not audit.is_file():
            self._permission_audit = (time.monotonic(), False)
            return False
        env = dict(os.environ)
        env["CODEX_THREAD_ID"] = self.source_task_id
        try:
            result = subprocess.run(
                [str(audit)],
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=15.0,
                check=False,
                env=env,
            )
            healthy = result.returncode == 0 and "FULL_ACCESS_PLUS=healthy" in (result.stdout or "")
        except (OSError, subprocess.SubprocessError):
            healthy = False
        self._permission_audit = (time.monotonic(), healthy)
        return healthy

    def _send_claude(self, target: dict, original: str, diagnostic: bool) -> tuple[str, dict]:
        node = shutil.which("node")
        if not node or not self.claude_sender.is_file():
            raise DispatchError("claude_bridge_unavailable", "The private local Claude session bridge is unavailable")
        if not self._permission_bypass_verified():
            raise DispatchError(
                "source_permission_mode_unverified",
                "The Dispatch source permission mode could not be verified; Claude delivery was refused.",
            )
        args = [
            node,
            str(self.claude_sender),
            "--session-id",
            target["id"],
            "--source-session-id",
            self.source_task_id,
            "--source-name",
            "Activity Monitor Dispatch",
            "--source-mode",
            "bypass",
            "--verify-ms",
            "8000",
        ]
        if diagnostic:
            args.append("--diagnostic")
        receipt: dict = {}
        try:
            result = subprocess.run(
                args,
                input=original,
                capture_output=True,
                text=True,
                timeout=15.0,
                check=False,
            )
        except OSError as error:
            raise DispatchError(
                "claude_delivery_failed",
                _safe_error(error),
                phase="exact-session delivery",
                delivery_attempted=False,
            ) from error
        except subprocess.SubprocessError as error:
            raise DispatchError(
                "claude_delivery_failed",
                _safe_error(error),
                phase="exact-session delivery",
                delivery_attempted=True,
                receipt={
                    "deliveryAttempted": True,
                    "retrySafe": False,
                    "reconciliationRequired": True,
                    "phase": "exact-session delivery",
                    "transport": "claude-private-session-socket",
                },
            ) from error
        raw_receipt = result.stdout or ""
        try:
            if len(raw_receipt.encode("utf-8")) > 65_536:
                raise ValueError("Claude receipt exceeds the bounded receipt limit")
            receipt = json.loads(raw_receipt)
            if not isinstance(receipt, dict):
                raise TypeError("Claude receipt is not an object")
        except (ValueError, TypeError, UnicodeError) as error:
            # The bridge process ran but returned no trustworthy pre-write
            # proof. Conservatively prevent a second send.
            raise DispatchError(
                "claude_receipt_invalid",
                _safe_error(error),
                phase="exact-session delivery",
                delivery_attempted=True,
                receipt={
                    "deliveryAttempted": True,
                    "retrySafe": False,
                    "reconciliationRequired": True,
                    "phase": "exact-session delivery",
                    "transport": "claude-private-session-socket",
                },
            ) from error
        socket_written = receipt.get("socketWritten") is True
        receipt_metadata = {
            "msgId": receipt.get("msgId"),
            "socketWritten": socket_written,
            "transcriptObserved": bool(receipt.get("transcriptObserved")),
            "contract": receipt.get("contract"),
            "deliveryAttempted": socket_written,
            "retrySafe": not socket_written,
            "reconciliationRequired": socket_written and not bool(receipt.get("transcriptObserved")),
            "phase": "exact-session delivery",
            "transport": "claude-private-session-socket",
        }
        if receipt.get("state") == "queued" and not socket_written:
            raise DispatchError(
                "claude_receipt_protocol_error",
                "Claude reported a queued delivery without confirming the socket write",
                phase="exact-session delivery",
                delivery_attempted=True,
                receipt={
                    **receipt_metadata,
                    "deliveryAttempted": True,
                    "retrySafe": False,
                    "reconciliationRequired": True,
                },
            )
        if result.returncode != 0 or receipt.get("state") != "queued":
            raise DispatchError(
                str(receipt.get("code") or "claude_delivery_failed"),
                _safe_error(receipt.get("message")),
                phase="exact-session delivery",
                delivery_attempted=socket_written,
                receipt=receipt_metadata,
            )
        if receipt.get("sessionId") != target["id"] or receipt.get("sourceSha256") != _sha256(original):
            raise DispatchError(
                "claude_receipt_mismatch",
                "Claude delivery receipt did not preserve exact identity",
                phase="exact-session delivery",
                delivery_attempted=socket_written,
                receipt=receipt_metadata,
            )
        state = "transcript observed" if receipt.get("transcriptObserved") else "queued"
        return state, receipt_metadata

    @staticmethod
    def _ipc_result(response: dict, method: str, owner_client_id: str) -> dict:
        if response.get("resultType") != "success":
            raise DispatchError("codex_owner_delivery_failed", DesktopIpcClient.error_text(response))
        if response.get("method") not in {None, method}:
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned the wrong method receipt")
        if response.get("handledByClientId") != owner_client_id:
            raise DispatchError("codex_owner_mismatch", "Codex desktop did not use the discovered task owner")
        value = response.get("result")
        if not isinstance(value, dict):
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned no owner result")
        nested = value.get("result")
        return nested if isinstance(nested, dict) else value

    @staticmethod
    def _inactive_steer_response(response: dict) -> bool:
        text = DesktopIpcClient.error_text(response)
        return bool(
            "SteerTurnInactiveError" in text
            or re.fullmatch(
                r"Cannot steer conversation [0-9a-f-]+ because its active turn already ended",
                text,
                flags=re.IGNORECASE,
            )
            or text.strip().lower() == "no active turn to steer"
        )

    def _try_desktop_codex(
        self,
        target: dict,
        original: str,
        diagnostic: bool,
    ) -> tuple[str, dict, None] | None:
        client = self.desktop_ipc_factory(self.desktop_ipc_path)
        try:
            try:
                discovery = client.request(
                    "thread-owner-discovery",
                    {"hostId": "local", "conversationId": target["id"]},
                    version=1,
                    timeout_ms=5000,
                )
            except DispatchError as error:
                # Owner discovery carries no message. A stale/not-loaded task
                # may therefore fall through once to exact app-server resume.
                # This exception is deliberately scoped to discovery; after a
                # steer/start request contains text, no fallback is allowed.
                if error.code in OWNER_DISCOVERY_FALLBACK_CODES:
                    return None
                raise
            if discovery.get("resultType") != "success":
                error_text = DesktopIpcClient.error_text(discovery).lower()
                if "no-client-found" in error_text:
                    return None
                raise DispatchError("codex_owner_discovery_failed", DesktopIpcClient.error_text(discovery))
            owner_client_id = str(discovery.get("handledByClientId") or "")
            if not UUID_RE.fullmatch(owner_client_id):
                raise DispatchError("codex_owner_discovery_failed", "Codex desktop returned no exact live owner")

            text = attributed_message(original, diagnostic)
            client_user_message_id = str(uuid.uuid4())
            restore_message_id = str(uuid.uuid4())
            cwd = str(target.get("_cwd") or self.home)
            if not Path(cwd).is_absolute():
                cwd = str(self.home)
            input_items = [{"type": "text", "text": text, "text_elements": []}]
            steer_params = {
                "conversationId": target["id"],
                "clientUserMessageId": client_user_message_id,
                "input": input_items,
                "attachments": [],
                "restoreMessage": {
                    "id": restore_message_id,
                    "text": text,
                    "context": {
                        "prompt": text,
                        "addedFiles": [],
                        "fileAttachments": [],
                        "ideContext": None,
                        "imageAttachments": [],
                        "workspaceRoots": [cwd],
                    },
                    "cwd": cwd,
                    "createdAt": int(time.time() * 1000),
                },
            }
            uncertain_receipt = {
                "clientUserMessageId": client_user_message_id,
                "ownerClientId": owner_client_id,
                "deliveryAttempted": True,
                "retrySafe": False,
                "reconciliationRequired": True,
                "phase": "exact-task resume/steer",
                "transport": "codex-desktop-owner-ipc",
                "providerPreserved": True,
            }
            try:
                steer = client.request(
                    "thread-follower-steer-turn",
                    steer_params,
                    version=1,
                    target_client_id=owner_client_id,
                    timeout_ms=12_000,
                )
            except DispatchError as error:
                raise DispatchError(
                    error.code,
                    str(error),
                    phase="exact-task resume/steer",
                    delivery_attempted=True,
                    receipt={**uncertain_receipt, "deliveryMode": "steer-uncertain"},
                ) from error
            delivery_mode = "steer"
            if steer.get("resultType") == "success":
                try:
                    result = self._ipc_result(steer, "thread-follower-steer-turn", owner_client_id)
                except DispatchError as error:
                    raise DispatchError(
                        error.code,
                        str(error),
                        phase="exact-task resume/steer",
                        delivery_attempted=True,
                        receipt={**uncertain_receipt, "deliveryMode": "steer-uncertain"},
                    ) from error
            elif self._inactive_steer_response(steer):
                try:
                    start = client.request(
                        "thread-follower-start-turn",
                        {
                            "conversationId": target["id"],
                            "turnStartParams": {
                                "input": input_items,
                                "clientUserMessageId": client_user_message_id,
                            },
                        },
                        version=1,
                        target_client_id=owner_client_id,
                        timeout_ms=12_000,
                    )
                    result = self._ipc_result(start, "thread-follower-start-turn", owner_client_id)
                except DispatchError as error:
                    raise DispatchError(
                        error.code,
                        str(error),
                        phase="exact-task resume/steer",
                        delivery_attempted=True,
                        receipt={**uncertain_receipt, "deliveryMode": "start-after-inactive-steer-uncertain"},
                    ) from error
                delivery_mode = "start-after-inactive-steer"
            else:
                raise DispatchError(
                    "codex_owner_delivery_failed",
                    DesktopIpcClient.error_text(steer),
                    phase="exact-task resume/steer",
                    delivery_attempted=True,
                    receipt={**uncertain_receipt, "deliveryMode": "steer-uncertain"},
                )

            turn = result.get("turn") if isinstance(result.get("turn"), dict) else result
            turn_id = str(turn.get("id") or turn.get("turnId") or result.get("turnId") or "")
            if not UUID_RE.fullmatch(turn_id):
                raise DispatchError(
                    "codex_turn_receipt_missing",
                    "Codex desktop returned no exact turn receipt",
                    phase="exact-task resume/steer",
                    delivery_attempted=True,
                    receipt={**uncertain_receipt, "deliveryMode": f"{delivery_mode}-receipt-uncertain"},
                )
            return "queued", {
                "turnId": turn_id,
                "clientUserMessageId": client_user_message_id,
                "desktopOwnerAccepted": True,
                "ownerClientId": owner_client_id,
                "deliveryMode": delivery_mode,
                "transport": "codex-desktop-owner-ipc",
                "providerPreserved": True,
                "deliveryAttempted": True,
                "retrySafe": False,
                "phase": "accepted",
            }, None
        finally:
            client.close()

    def _start_codex(
        self,
        target: dict,
        original: str,
        diagnostic: bool,
    ) -> tuple[str, dict, CodexAppServerClient | None]:
        desktop_result = self._try_desktop_codex(target, original, diagnostic)
        if desktop_result is not None:
            return desktop_result
        if not self.codex_command:
            raise DispatchError("codex_app_server_unavailable", "Codex app-server is unavailable")
        client = CodexAppServerClient(self.codex_command)
        try:
            client.start()
            resumed = client.request(
                "thread/resume",
                {"threadId": target["id"], "excludeTurns": True},
                timeout=8.0,
            )
            thread = resumed.get("thread") or {}
            if thread.get("id") != target["id"]:
                raise DispatchError("codex_identity_mismatch", "Codex resumed a different task")
            expected_provider = target.get("modelProvider")
            actual_provider = str(resumed.get("modelProvider") or thread.get("modelProvider") or "")
            if expected_provider and actual_provider and actual_provider != expected_provider:
                raise DispatchError("codex_provider_mismatch", "Codex provider identity changed during resume")
            client_message_id = str(uuid.uuid4())
            try:
                response = client.request(
                    "turn/start",
                    {
                        "threadId": target["id"],
                        "input": [
                            {
                                "type": "text",
                                "text": attributed_message(original, diagnostic),
                                "text_elements": [],
                            }
                        ],
                        "clientUserMessageId": client_message_id,
                    },
                    timeout=12.0,
                )
            except DispatchError as error:
                raise DispatchError(
                    error.code,
                    str(error),
                    phase="exact-task resume/steer",
                    delivery_attempted=True,
                    receipt={
                        "clientUserMessageId": client_message_id,
                        "deliveryAttempted": True,
                        "retrySafe": False,
                        "reconciliationRequired": True,
                        "phase": "exact-task resume/steer",
                        "deliveryMode": "app-server-start-uncertain",
                        "transport": "codex-exact-thread-app-server",
                        "providerPreserved": True,
                    },
                ) from error
            turn = response.get("turn") or {}
            turn_id = str(turn.get("id") or "")
            if not UUID_RE.fullmatch(turn_id):
                raise DispatchError(
                    "codex_turn_receipt_missing",
                    "Codex did not return an exact turn receipt",
                    phase="exact-task resume/steer",
                    delivery_attempted=True,
                    receipt={
                        "clientUserMessageId": client_message_id,
                        "deliveryAttempted": True,
                        "retrySafe": False,
                        "reconciliationRequired": True,
                        "phase": "exact-task resume/steer",
                        "deliveryMode": "app-server-start-receipt-uncertain",
                        "transport": "codex-exact-thread-app-server",
                        "providerPreserved": True,
                    },
                )
            return "queued", {
                "turnId": turn_id,
                "clientUserMessageId": client_message_id,
                "appServerAccepted": True,
                "transport": "codex-exact-thread-app-server",
                "providerPreserved": True,
                "deliveryAttempted": True,
                "retrySafe": False,
                "phase": "accepted",
            }, client
        except Exception:
            client.close()
            raise

    def _rollout_contains_id(self, path_value: str, client_user_message_id: str) -> bool:
        try:
            path = Path(path_value).expanduser().resolve(strict=True)
            root = (self.home / ".codex" / "sessions").resolve(strict=True)
            path.relative_to(root)
            metadata = path.stat()
            if not path.is_file() or metadata.st_uid != os.getuid():
                return False
            with path.open("rb") as handle:
                handle.seek(max(0, metadata.st_size - 2 * 1024 * 1024))
                return client_user_message_id.encode("ascii") in handle.read(2 * 1024 * 1024)
        except (OSError, ValueError, UnicodeError):
            return False

    def _claude_transcript_contains_id(
        self,
        project_key: str,
        session_id: str,
        message_id: str,
    ) -> bool:
        if (
            not re.fullmatch(r"[A-Za-z0-9-]{1,4096}", str(project_key or ""))
            or not UUID_RE.fullmatch(str(session_id or ""))
            or not UUID_RE.fullmatch(str(message_id or ""))
        ):
            return False
        descriptors: list[int] = []
        flags_directory = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
        try:
            root = self.home / ".claude" / "projects"
            root_fd = os.open(root, flags_directory)
            descriptors.append(root_fd)
            root_metadata = os.fstat(root_fd)
            if (
                not stat.S_ISDIR(root_metadata.st_mode)
                or root_metadata.st_uid != os.getuid()
                or stat.S_IMODE(root_metadata.st_mode) & 0o077
            ):
                return False
            project_fd = os.open(project_key, flags_directory, dir_fd=root_fd)
            descriptors.append(project_fd)
            project_metadata = os.fstat(project_fd)
            if (
                not stat.S_ISDIR(project_metadata.st_mode)
                or project_metadata.st_uid != os.getuid()
                or stat.S_IMODE(project_metadata.st_mode) & 0o077
            ):
                return False
            file_flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
            transcript_fd = os.open(f"{session_id}.jsonl", file_flags, dir_fd=project_fd)
            descriptors.append(transcript_fd)
            transcript_metadata = os.fstat(transcript_fd)
            if not stat.S_ISREG(transcript_metadata.st_mode) or transcript_metadata.st_uid != os.getuid():
                return False
            tail_bytes = min(max(0, transcript_metadata.st_size), 2 * 1024 * 1024)
            os.lseek(transcript_fd, max(0, transcript_metadata.st_size - tail_bytes), os.SEEK_SET)
            needle = message_id.encode("ascii")
            overlap = b""
            remaining = tail_bytes
            while remaining > 0:
                chunk = os.read(transcript_fd, min(16_384, remaining))
                if not chunk:
                    break
                if needle in overlap + chunk:
                    return True
                overlap = (overlap + chunk)[-max(0, len(needle) - 1):]
                remaining -= len(chunk)
            return False
        except (OSError, ValueError, UnicodeError):
            return False
        finally:
            for descriptor in reversed(descriptors):
                try:
                    os.close(descriptor)
                except OSError:
                    pass

    def _monitor_ipc_transcript(
        self,
        entry_id: str,
        rollout_path: str,
        client_user_message_id: str,
    ) -> None:
        deadline = time.monotonic() + min(self.monitor_seconds, 60.0)
        while time.monotonic() < deadline:
            if self._rollout_contains_id(rollout_path, client_user_message_id):
                self._update_history(
                    entry_id,
                    "transcript observed",
                    {"transcriptMetadataObserved": True},
                )
                return
            time.sleep(0.25)
        self._update_history(entry_id, "accepted", {"transcriptObservationTimedOut": True})

    def _monitor_uncertain_transcript(
        self,
        entry_id: str,
        rollout_path: str,
        client_user_message_id: str,
    ) -> None:
        deadline = time.monotonic() + min(self.monitor_seconds, 60.0)
