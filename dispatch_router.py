def _utc_now() -> str:
    return datetime.now(tz=timezone.utc).isoformat().replace("+00:00", "Z")


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _tokens(text: str) -> set[str]:
    return {
        value
        for value in re.findall(r"[a-z0-9][a-z0-9._+-]{2,}", str(text or "").lower())
        if value not in STOP_WORDS and not UUID_RE.fullmatch(value)
    }


def _safe_error(value: object, limit: int = 280) -> str:
    text = re.sub(r"\s+", " ", str(value or "")).strip()
    return text[:limit] or "Dispatch operation failed"


def attributed_message(original: str, diagnostic: bool = False) -> str:
    """Preserve the original text exactly after a fixed attribution."""
    return (DIAGNOSTIC_PREFACE if diagnostic else OPERATOR_PREFACE) + original


class DispatchError(RuntimeError):
    def __init__(
        self,
        code: str,
        message: str,
        *,
        phase: str | None = None,
        delivery_attempted: bool = False,
        receipt: dict | None = None,
    ):
        super().__init__(message)
        self.code = code
        self.phase = phase
        self.delivery_attempted = bool(delivery_attempted)
        self.receipt = dict(receipt or {})


class DesktopIpcClient:
    """Authenticated client for the Codex desktop owner's local IPC router."""

    def __init__(self, socket_path: str | Path, request_timeout: float = 6.0):
        self.socket_path = Path(socket_path).expanduser()
        self.request_timeout = max(0.5, float(request_timeout))
        self.socket: socket.socket | None = None
        self.client_id: str | None = None

    def _validate_socket(self) -> None:
        try:
            metadata = self.socket_path.lstat()
        except FileNotFoundError as error:
            raise DispatchError("desktop_ipc_unavailable", "The Codex desktop IPC socket is unavailable") from error
        except OSError as error:
            raise DispatchError("desktop_ipc_unavailable", _safe_error(error)) from error
        if not stat.S_ISSOCK(metadata.st_mode):
            raise DispatchError("desktop_ipc_insecure", "The Codex desktop IPC path is not a socket")
        if metadata.st_uid != os.getuid() or metadata.st_mode & 0o077:
            raise DispatchError(
                "desktop_ipc_insecure",
                "The Codex desktop IPC socket is not private to the current user",
            )

    def connect(self) -> None:
        if self.socket is not None:
            return
        self._validate_socket()
        client = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        client.settimeout(self.request_timeout)
        try:
            client.connect(str(self.socket_path))
        except OSError as error:
            client.close()
            raise DispatchError("desktop_ipc_unavailable", _safe_error(error)) from error
        self.socket = client
        response = self._request(
            "initialize",
            {"clientType": "activity-monitor-dispatch"},
            version=0,
            include_source=False,
        )
        if response.get("resultType") != "success":
            self.close()
            raise DispatchError("desktop_ipc_initialize_failed", self.error_text(response))
        result = response.get("result") or {}
        client_id = str(result.get("clientId") or "") if isinstance(result, dict) else ""
        if not UUID_RE.fullmatch(client_id):
            self.close()
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned no exact client identity")
        self.client_id = client_id

    def _read_exact(self, size: int) -> bytes:
        client = self.socket
        if client is None:
            raise DispatchError("desktop_ipc_closed", "Codex desktop IPC is not connected")
        chunks: list[bytes] = []
        remaining = size
        while remaining:
            try:
                chunk = client.recv(remaining)
            except (OSError, socket.timeout) as error:
                raise DispatchError("desktop_ipc_read_failed", _safe_error(error)) from error
            if not chunk:
                raise DispatchError("desktop_ipc_closed", "Codex desktop IPC closed before responding")
            chunks.append(chunk)
            remaining -= len(chunk)
        return b"".join(chunks)

    def _read_message(self) -> dict:
        frame_size = struct.unpack("<I", self._read_exact(4))[0]
        if frame_size <= 0 or frame_size > MAX_IPC_FRAME_BYTES:
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned an invalid IPC frame")
        try:
            value = json.loads(self._read_exact(frame_size).decode("utf-8"))
        except (UnicodeError, ValueError, TypeError) as error:
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned invalid JSON") from error
        if not isinstance(value, dict):
            raise DispatchError("desktop_ipc_protocol_error", "Codex desktop returned a non-object response")
        return value

    def _write_message(self, value: dict) -> None:
        client = self.socket
        if client is None:
            raise DispatchError("desktop_ipc_closed", "Codex desktop IPC is not connected")
        encoded = json.dumps(value, separators=(",", ":")).encode("utf-8")
        if len(encoded) > MAX_IPC_FRAME_BYTES:
            raise DispatchError("desktop_ipc_frame_too_large", "The Codex desktop IPC request is too large")
        try:
            client.sendall(struct.pack("<I", len(encoded)) + encoded)
        except OSError as error:
            raise DispatchError("desktop_ipc_write_failed", _safe_error(error)) from error

    def _request(
        self,
        method: str,
        params: dict,
        *,
        version: int,
        target_client_id: str | None = None,
        timeout_ms: int = 6000,
        include_source: bool = True,
    ) -> dict:
        request_id = str(uuid.uuid4())
        request = {
            "type": "request",
            "requestId": request_id,
            "version": int(version),
            "method": method,
            "params": params,
            "timeoutMs": int(timeout_ms),
        }
        if include_source:
            if not self.client_id:
                raise DispatchError("desktop_ipc_protocol_error", "Codex desktop client is not initialized")
            request["sourceClientId"] = self.client_id
        if target_client_id:
            request["targetClientId"] = target_client_id
        if self.socket is not None:
            self.socket.settimeout(max(self.request_timeout, timeout_ms / 1000 + 1.0))
        self._write_message(request)
        deadline = time.monotonic() + max(0.5, timeout_ms / 1000 + 1.0)
        while time.monotonic() < deadline:
            response = self._read_message()
            if response.get("type") == "response" and response.get("requestId") == request_id:
                return response
        raise DispatchError("desktop_ipc_timeout", f"Timed out during {method}")

    def request(
        self,
        method: str,
        params: dict,
        *,
        version: int = 1,
        target_client_id: str | None = None,
        timeout_ms: int = 6000,
    ) -> dict:
        self.connect()
        return self._request(
            method,
            params,
            version=version,
            target_client_id=target_client_id,
            timeout_ms=timeout_ms,
        )

    @staticmethod
    def error_text(response: dict) -> str:
        for key in ("error", "message", "result"):
            value = response.get(key)
            if value:
                return _safe_error(json.dumps(value, sort_keys=True) if isinstance(value, (dict, list)) else value)
        return "Codex desktop IPC request failed"

    def close(self) -> None:
        client, self.socket = self.socket, None
        self.client_id = None
        if client is not None:
            try:
                client.close()
            except OSError:
                pass


class CodexAppServerClient:
    """Small JSONL client for the supported experimental Codex app-server API."""

    def __init__(self, command: str, request_timeout: float = 6.0):
        self.command = command
        self.request_timeout = max(0.5, float(request_timeout))
        self.process: subprocess.Popen | None = None
        self._waiters: dict[int, queue.Queue] = {}
        self._waiters_lock = threading.Lock()
        self._write_lock = threading.Lock()
        self._notifications: queue.Queue = queue.Queue()
        self._next_id = 1
        self._stderr_tail: list[str] = []

    def start(self) -> None:
        if self.process and self.process.poll() is None:
            return
        try:
            self.process = subprocess.Popen(
                [self.command, "app-server", "--stdio"],
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                bufsize=1,
            )
        except OSError as error:
            raise DispatchError("codex_app_server_unavailable", _safe_error(error)) from error
        threading.Thread(target=self._read_stdout, daemon=True).start()
        threading.Thread(target=self._read_stderr, daemon=True).start()
        self.request(
            "initialize",
            {
                "clientInfo": {
                    "name": "ke_activity_monitor_dispatch",
                    "title": "Activity Monitor Dispatch",
                    "version": "2.7.0",
                },
                "capabilities": {"experimentalApi": True},
            },
        )
        self.notify("initialized", {})

    def _read_stdout(self) -> None:
        process = self.process
        if not process or not process.stdout:
            return
        for line in process.stdout:
            try:
                message = json.loads(line)
            except (ValueError, TypeError):
                continue
            response_id = message.get("id")
            if response_id is not None:
                with self._waiters_lock:
                    waiter = self._waiters.get(response_id)
                if waiter:
                    waiter.put(message)
                    continue
            self._notifications.put(message)
        self._notifications.put({"method": "_process/closed", "params": {}})

    def _read_stderr(self) -> None:
        process = self.process
        if not process or not process.stderr:
            return
        for line in process.stderr:
            self._stderr_tail.append(_safe_error(line, 400))
            del self._stderr_tail[:-8]

    def request(self, method: str, params: dict | None = None, timeout: float | None = None) -> dict:
        process = self.process
        if not process or process.poll() is not None or not process.stdin:
            raise DispatchError("codex_app_server_closed", "Codex app-server is not running")
        with self._write_lock:
            request_id = self._next_id
            self._next_id += 1
            waiter: queue.Queue = queue.Queue(maxsize=1)
            with self._waiters_lock:
                self._waiters[request_id] = waiter
            try:
                process.stdin.write(
                    json.dumps(
                        {"jsonrpc": "2.0", "id": request_id, "method": method, "params": params or {}},
                        separators=(",", ":"),
                    )
                    + "\n"
                )
                process.stdin.flush()
            except OSError as error:
                with self._waiters_lock:
                    self._waiters.pop(request_id, None)
                raise DispatchError("codex_app_server_write_failed", _safe_error(error)) from error
        try:
            response = waiter.get(timeout=timeout or self.request_timeout)
        except queue.Empty as error:
            detail = self._stderr_tail[-1] if self._stderr_tail else f"Timed out during {method}"
            raise DispatchError("codex_app_server_timeout", detail) from error
        finally:
            with self._waiters_lock:
                self._waiters.pop(request_id, None)
        if response.get("error"):
            error = response["error"]
            message = _safe_error(error.get("message") if isinstance(error, dict) else error)
            lowered = message.lower()
            if "active writer" in lowered or "already running" in lowered or "in use" in lowered:
                raise DispatchError(
                    "busy_exact_task_unsupported",
                    "That exact Codex task is held by another app writer; Dispatch refused to create a companion.",
                )
            raise DispatchError("codex_request_failed", message)
        result = response.get("result")
        if not isinstance(result, dict):
            raise DispatchError("codex_protocol_error", f"{method} returned no object result")
        return result

    def notify(self, method: str, params: dict | None = None) -> None:
        process = self.process
        if not process or process.poll() is not None or not process.stdin:
            raise DispatchError("codex_app_server_closed", "Codex app-server is not running")
        with self._write_lock:
            process.stdin.write(
                json.dumps(
                    {"jsonrpc": "2.0", "method": method, "params": params or {}},
                    separators=(",", ":"),
                )
                + "\n"
            )
            process.stdin.flush()

    def next_notification(self, timeout: float = 1.0) -> dict | None:
        try:
            return self._notifications.get(timeout=max(0.05, timeout))
        except queue.Empty:
            return None

    def close(self) -> None:
        process = self.process
        if not process:
            return
        if process.poll() is None:
            try:
                process.terminate()
                process.wait(timeout=1.5)
            except (OSError, subprocess.TimeoutExpired):
                try:
                    process.kill()
                except OSError:
                    pass
        self.process = None


class DispatchService:
    """Resolve exactly one existing owner and deliver without provider substitution."""

    def __init__(
        self,
        *,
        home: str | Path | None = None,
        history_path: str | Path | None = None,
        brain_service=None,
        workspace_service=None,
        codex_command: str | None = None,
        board_command: list[str] | None = None,
        claude_sender: str | Path | None = None,
        desktop_ipc_path: str | Path | None = None,
        desktop_ipc_factory=DesktopIpcClient,
        source_task_id: str = "01a020e9-efef-70c0-8aee-5370b9867bb0",
        monitor_seconds: float = 1800.0,
    ):
        self.home = Path(home or Path.home()).expanduser().resolve()
        support = self.home / "Library" / "Application Support" / "KE Studios" / "Activity Monitor"
        self.history_path = Path(history_path or support / "dispatch-history.json").expanduser()
        self.brain_service = brain_service
        self.workspace_service = workspace_service
        self.codex_command = self._validated_executable(codex_command or self._find_codex_command())
        self.board_command = board_command or [
            "/usr/bin/python3",
            str(self.home / "ke-agent-rooms" / "board" / "boardctl.py"),
            "status",
            "--event-limit",
            "0",
        ]
        self.claude_sender = Path(
            claude_sender
            or self.home / ".codex" / "skills" / "dispatch-chat" / "scripts" / "send_claude_session.mjs"
        )
        self.desktop_ipc_path = Path(desktop_ipc_path or self.home / ".codex" / "ipc" / "ipc.sock")
        self.desktop_ipc_factory = desktop_ipc_factory
        self.source_task_id = source_task_id
        self.monitor_seconds = max(5.0, float(monitor_seconds))
        self._lock = threading.RLock()
        self._resolutions: dict[str, dict] = {}
        self._clients: dict[str, CodexAppServerClient] = {}
        # None means no permission audit has completed. A numeric sentinel such
        # as 0.0 is unsafe because time.monotonic() can also be near zero in a
        # newly started interpreter, which would incorrectly cache a failure.
        self._permission_audit: tuple[float | None, bool] = (None, False)

    def _find_codex_command(self) -> str | None:
        found = shutil.which("codex")
        if found:
            return found
        candidates = [
            self.home / ".local" / "bin" / "codex",
            self.home / ".codex" / "packages" / "standalone" / "current" / "bin" / "codex",
        ]
        return next((str(path) for path in candidates if path.is_file()), None)

    @staticmethod
    def _validated_executable(command: str | None) -> str | None:
        """Resolve only a fixed root/current-user executable for app-server launch."""
        if not command:
            return None
        try:
            path = Path(command).expanduser().resolve(strict=True)
            metadata = path.stat()
        except OSError:
            return None
        if (
            not stat.S_ISREG(metadata.st_mode)
            or metadata.st_uid not in {0, os.getuid()}
            or metadata.st_mode & 0o022
            or not os.access(path, os.X_OK)
        ):
            return None
        return str(path)

    @staticmethod
    def _open_private_directory(path: str | Path, *, dir_fd: int | None = None) -> int:
        flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
        descriptor = os.open(path, flags, dir_fd=dir_fd)
        metadata = os.fstat(descriptor)
        if (
            not stat.S_ISDIR(metadata.st_mode)
            or metadata.st_uid != os.getuid()
            or stat.S_IMODE(metadata.st_mode) & 0o077
        ):
            os.close(descriptor)
            raise OSError("directory is not private current-user metadata")
        return descriptor

    @staticmethod
    def _open_history_directory(path: str | Path) -> int:
        """Open an existing support directory without hiding safe 0755 upgrades."""
        flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
        descriptor = os.open(path, flags)
        metadata = os.fstat(descriptor)
        if (
            not stat.S_ISDIR(metadata.st_mode)
            or metadata.st_uid != os.getuid()
            or stat.S_IMODE(metadata.st_mode) & 0o022
        ):
            os.close(descriptor)
            raise OSError("history directory is not a safe current-user support directory")
        return descriptor

    def _read_history_checked(self) -> tuple[dict, str | None]:
        """Return healthy history or a fail-closed status for an existing bad store.

        A genuinely missing file is the normal first-launch state. Once a
        history path exists, any trust, permission, size, schema, or decoding
        failure may conceal a prior attempted receipt and must disable sends.
        """
        defaults = {"schemaVersion": HISTORY_SCHEMA_VERSION, "entries": []}
        descriptors: list[int] = []
        try:
            try:
                parent_fd = self._open_history_directory(self.history_path.parent)
            except FileNotFoundError:
                return defaults, None
            except OSError:
                return defaults, "dispatch_history_unavailable"
            descriptors.append(parent_fd)
            flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
            try:
                history_fd = os.open(self.history_path.name, flags, dir_fd=parent_fd)
            except FileNotFoundError:
                return defaults, None
            except OSError:
                return defaults, "dispatch_history_unavailable"
            descriptors.append(history_fd)
            metadata = os.fstat(history_fd)
            if (
                not stat.S_ISREG(metadata.st_mode)
                or metadata.st_uid != os.getuid()
                or stat.S_IMODE(metadata.st_mode) != 0o600
                or metadata.st_size < 2
                or metadata.st_size > 2 * 1024 * 1024
            ):
                return defaults, "dispatch_history_unavailable"
            chunks: list[bytes] = []
            remaining = metadata.st_size
            while remaining > 0:
                chunk = os.read(history_fd, min(16_384, remaining))
                if not chunk:
                    break
                chunks.append(chunk)
                remaining -= len(chunk)
            value = json.loads(b"".join(chunks).decode("utf-8"))
            entries = value.get("entries") if isinstance(value, dict) else None
            if (
                value.get("schemaVersion") != HISTORY_SCHEMA_VERSION
                or not isinstance(entries, list)
                or len(entries) > MAX_HISTORY_ENTRIES
                or any(not isinstance(entry, dict) for entry in entries)
            ):
                return defaults, "dispatch_history_unavailable"
            return value, None
        except (OSError, ValueError, TypeError, AttributeError, UnicodeError):
            return defaults, "dispatch_history_unavailable"
        finally:
            for descriptor in reversed(descriptors):
                try:
                    os.close(descriptor)
                except OSError:
                    pass

    def _read_history(self) -> dict:
        return self._read_history_checked()[0]

    @staticmethod
    def _history_error() -> DispatchError:
        return DispatchError(
            "dispatch_history_unavailable",
            "Existing Dispatch receipt history is unavailable or untrusted; no new delivery started, and sending is disabled until the local metadata-only history is repaired or reconciled",
            phase="history reconciliation",
            delivery_attempted=False,
            receipt={
                "phase": "history reconciliation",
                "deliveryAttempted": False,
                "retrySafe": False,
                "reconciliationRequired": True,
            },
        )

    def _write_history(self, value: dict) -> None:
        self.history_path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        _current, issue = self._read_history_checked()
        if issue:
            raise OSError("existing dispatch history is unavailable or untrusted")
        parent_fd = self._open_history_directory(self.history_path.parent)
        temporary_name = self.history_path.name + ".tmp-" + secrets.token_hex(4)
        descriptor = -1
        try:
            flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
            descriptor = os.open(temporary_name, flags, 0o600, dir_fd=parent_fd)
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                descriptor = -1
                json.dump(value, handle, indent=2, sort_keys=True)
                handle.write("\n")
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(
                temporary_name,
                self.history_path.name,
                src_dir_fd=parent_fd,
                dst_dir_fd=parent_fd,
            )
            os.chmod(self.history_path.name, 0o600, dir_fd=parent_fd, follow_symlinks=False)
            os.fsync(parent_fd)
        finally:
            if descriptor >= 0:
                os.close(descriptor)
            try:
                os.unlink(temporary_name, dir_fd=parent_fd)
            except FileNotFoundError:
                pass
            os.close(parent_fd)

    def _history_entry(
        self,
        target: dict | None,
        sha256: str,
        reason: str,
        state: str,
        diagnostic: bool,
        receipt: dict | None = None,
    ) -> dict:
        if state not in ALLOWED_STATES:
            raise ValueError(f"Unsupported dispatch state: {state}")
        now = _utc_now()
        entry = {
            "id": "dispatch_" + secrets.token_hex(10),
            "timestamp": now,
            "provider": target.get("providerLabel") if target else None,
            "destinationTitle": target.get("title") if target else None,
            "destinationId": target.get("id") if target else None,
            "routingReason": reason,
            "state": state,
            "sha256": sha256,
            "diagnostic": bool(diagnostic),
            "phases": [{"state": state, "at": now}],
            "receipt": self._receipt_metadata(receipt),
        }
        with self._lock:
            history, issue = self._read_history_checked()
            if issue:
                raise self._history_error()
            history["entries"] = [entry, *history["entries"]][:MAX_HISTORY_ENTRIES]
            try:
                self._write_history(history)
            except OSError as error:
                raise self._history_error() from error
        return entry

    def _update_history(self, entry_id: str, state: str, receipt: dict | None = None) -> bool:
        if state not in ALLOWED_STATES:
            return False
        with self._lock:
            history, issue = self._read_history_checked()
            if issue:
                return False
            updated = False
            for entry in history["entries"]:
                if entry.get("id") != entry_id:
                    continue
                if entry.get("state") != state:
                    entry["state"] = state
                    entry.setdefault("phases", []).append({"state": state, "at": _utc_now()})
                if receipt:
                    entry.setdefault("receipt", {}).update(self._receipt_metadata(receipt))
                updated = True
                break
            if not updated:
                return False
            try:
                self._write_history(history)
            except OSError:
                return False
            return True

